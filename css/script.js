/* ================= SEARCH ================= */

function searchPlace() {

    const input =
        document
            .getElementById("searchInput")
            .value
            .toLowerCase()
            .trim();

    const message =
        document.getElementById("message");


    if (input === "") {

        message.innerText =
            "Please enter a destination.";

        return;
    }


    if (input.includes("manali")) {

        showPlace("manali");

        message.innerText = "";

    }

    else if (input.includes("goa")) {

        showPlace("goa");

        message.innerText = "";

    }

    else if (input.includes("jaipur")) {

        showPlace("jaipur");

        message.innerText = "";

    }

    else if (input.includes("kerala")) {

        showPlace("kerala");

        message.innerText = "";

    }

    else if (input.includes("hyderabad")) {

        showPlace("hyderabad");

        message.innerText = "";

    }

    else {

        message.innerText =
            "❌ Destination not found. Try Manali, Goa, Jaipur, Kerala or Hyderabad.";

    }

}


/* ================= ENTER KEY SEARCH ================= */

document
    .getElementById("searchInput")
    .addEventListener("keydown", function(event) {

        if (event.key === "Enter") {
            searchPlace();
        }

    });
